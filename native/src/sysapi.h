// מה שהתוכנה צריכה ממערכת ההפעלה מעבר לקבצים ולרשת: מסירת כתובת
// לאוצריא, דיאלוג שמירה, קריאת גרסה מ-exe, רישומי ההסרה שברג'יסטרי,
// זיהוי תהליך אוצריא הרץ, ומצב הערכה הכהה.
//
// ── מה כאן שיפור מול גרסת ה-Flutter ─────────────────────────────────────────
// שלוש מהפונקציות האלה היו שם FFI מעל `package:win32`, ואחת מהן
// (`WindowsExeVersionReader`) נשאה בתיעוד שלה הודעה שהיא **לא נבדקה על
// ווינדוס בפועל**. כאן הן קריאות Win32 ישירות.
//
// [FindRunningOtzaria] גם אינו מריץ עוד `tasklist` כתהליך-בן: הוא
// משתמש ב-Toolhelp snapshot. זו הייתה הפעולה היקרה ביותר בעליית
// הלאנצ'ר (~300ms), וכאן היא כמעט חינם.
#pragma once

// מביא את `windows.h` — [SaveFileDialog] מקבל `HWND`.
#include "common.h"

#include <string>
#include <vector>

#include "fsapi.h"

namespace otz::sysapi {

// מאתחל COM עבור התהליך (נדרש ל-ShellExecute ולדיאלוג השמירה). נקרא
// פעם אחת מה-thread של הממשק.
bool Init();

// ── מסירת ההתקנה לאוצריא ─────────────────────────────────────────────────────

// פותח כתובת דרך מטפל הפרוטוקול של מערכת ההפעלה (`otzaria://…`), או
// דפדפן (`https://…`).
Result OpenExternalUrl(const std::wstring& url);

// מריץ את [exe_path] עם [argument] כארגומנט יחיד, **מנותק**.
//
// זהו המסלול שגורם להתקנה בהתקנה **ניידת** לעבוד: היא אינה רושמת את
// הסכימה `otzaria://` בכלל, ולכן מסירה למערכת ההפעלה נכשלה שם
// ב"ודא שאוצריא מותקנת". כאן ה-URL נמסר לקובץ ההרצה עצמו — בדיוק מה
// שהרישום ברג'יסטרי היה עושה (`"otzaria.exe" "%1"`).
//
// מנותק ולא ממתין: אוצריא נשארת פתוחה אחרי שהחנות תיסגר.
Result LaunchDetached(const std::wstring& exe_path, const std::wstring& argument);

// ── דיאלוג שמירה ─────────────────────────────────────────────────────────────

// "שמור עותק" של קובץ ה-.otzplugin. מחזיר את הנתיב שנבחר, או `null`
// (כ-JSON) כשהמשתמש ביטל — ביטול אינו שגיאה.
//
// ⚠️ חייב לרוץ על ה-thread של הממשק: זהו דיאלוג מודאלי של COM/STA.
// הגשר מפנה אותו לשם.
Result SaveFileDialog(HWND owner, const std::wstring& suggested_name);

// ── זיהוי ההתקנה של אוצריא ───────────────────────────────────────────────────

// ה-`ProductVersion` המוטבע ב-version resource של [exe_path], או `null`
// כשאין. זו הגרסה שנקראת **מההתקנה עצמה** — לא ממה שנרשם בקובץ מצב
// ולא מ-`DisplayVersion` שברג'יסטרי.
Result ReadExeProductVersion(const std::wstring& exe_path);

// תיקיות ההתקנה מרישומי ההסרה של ווינדוס, שה-`DisplayName` שלהם מזכיר
// את אוצריא. מוחזרת רק תיקייה מוחלטת שקיימת בפועל.
//
// זה המקום היחיד שיודע על התקנה שאינה באחת מתיקיות ברירת המחדל — גם
// כשאוצריא סגורה, בשונה מזיהוי לפי התהליך הרץ.
Result OtzariaRegistryInstallDirs();

// `{running, launchPath}` — התהליך הרץ של אוצריא.
//
// `launchPath` יכול להיות `null` גם כש-`running` הוא `true`: תהליך שרץ
// מוגבה (כמנהל) מזוהה כרץ, אבל הנתיב שלו אינו קריא. שני השדות אינם
// חופפים, בדיוק כמו `RunningOtzariaProbe` בגרסת ה-Flutter.
Result FindRunningOtzaria();

// ── ערכת הנושא של המערכת ─────────────────────────────────────────────────────

// `true` כשווינדוס במצב כהה עבור אפליקציות. החנות אינה נותנת לבחור
// ערכה — היא הולכת אחרי המערכת, כמו בגרסת ה-Flutter.
bool IsSystemDarkMode();

}  // namespace otz::sysapi
