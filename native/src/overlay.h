// המראה שנוסעת **בתוך** קובץ ההרצה: זיהוי, פריסה לדיסק, ועותק רזה.
//
// ── מה זה פותר ───────────────────────────────────────────────────────────────
// התוכנה עצמה היא ‎0.5MB, אבל המראה שהיא מסנכרנת היא ~‎96MB — וזה בדיוק
// מה שאי אפשר להוריד במחשב מנותק. לכן קיימת **חבילה**: אותו exe בדיוק,
// עם המראה משורשרת לסופו. בהרצה הראשונה הוא פורס אותה לתיקייה שלידו,
// כותב לצדו עותק רזה של עצמו (בלי המטען), מפעיל אותו ויוצא.
//
// מכאן והלאה מה שרץ הוא ה-exe הרזה, והחבילה הגדולה היא קובץ מיותר
// שהמשתמש יכול למחוק — הממשק מציע לו את זה (ראו `installerPath`
// שב-`app.info`).
//
// ── הפורמט ───────────────────────────────────────────────────────────────────
// נקבע ב-native/tools/pack_overlay.mjs, וכל שינוי בו חייב לקרות בשני
// המקומות:
//
//   [ ה-exe המקורי, ללא שינוי ]
//   [ תוכן הקבצים, ברצף, בסדר האינדקס, **בלי דחיסה** ]
//   [ אינדקס: count(u32), ואז לכל קובץ path_len(u32) size(u64) path(utf8) ]
//   [ footer: 96 בייט קבועים בסוף הקובץ ]
//
// ה-footer בסוף ובגודל קבוע כדי שהזיהוי יהיה קפיצה אחת: קובץ שאין בו
// חבילה עולה כאן קריאה של 96 בייט, ולא סריקה.
//
// ── למה אין תיקייה זמנית ואין דחיסה ──────────────────────────────────────────
// **דחיסה** אינה מחזירה כאן דבר: ה-`.otzplugin` הם ZIP והתמונות הן
// webp/png. גולמי פירושו שהפריסה היא העתקה **בזרימה** בחוצץ קבוע, ולא
// פרישה של ‎96MB לזיכרון.
//
// **תיקייה זמנית** הייתה דורשת ‎96MB פנויים נוספים על כונן נייד, וזה לא
// מחיר סביר. האטומיות מגיעה מסדר הפעולות במקום: קובץ החותמת נמחק לפני
// הפריסה ונכתב רק אחרי שהקובץ האחרון נחת. פריסה שנקטעה = אין חותמת =
// ההרצה הבאה עושה אותה מחדש, וזה כל מה שצריך.
#pragma once

// מביא את `windows.h` — [ProgressWindow] מחזיק `HWND` ו-`HINSTANCE`.
#include "common.h"

#include <cstdint>
#include <functional>
#include <string>

namespace otz {

// חייב להתאים ל-`MAGIC` ו-`FOOTER_SIZE` שב-native/tools/pack_overlay.mjs.
inline constexpr char kOverlayMagic[8] = {'O', 'T', 'Z', 'B', 'N', 'D', 'L', '1'};
inline constexpr uint64_t kOverlayFooterSize = 96;

// אורך החותמת: SHA-256 בייצוג hex.
inline constexpr size_t kOverlayStampChars = 64;

// קובץ החותמת, בתוך `Data\`. שתי שורות — ראו [StampFile].
inline constexpr wchar_t kStampFileName[] = L"bundle.stamp";

// מה שה-footer מספר על החבילה. נקרא פעם אחת בעלייה.
struct OverlayInfo {
  // גודל ה-exe **בלי** המטען — כלומר גם מספר הבייטים שהעותק הרזה מכיל.
  uint64_t data_offset = 0;

  // איפה מתחיל האינדקס, וכמה הוא. גם סוף אזור התוכן.
  uint64_t index_offset = 0;
  uint64_t index_size = 0;

  // גודל התוכן עצמו — `index_offset - data_offset`. זה המכנה של
  // ההתקדמות, ולכן הוא נגזר כאן פעם אחת ולא בכל קריאה.
  uint64_t payload_size = 0;

  // מזהה החבילה: 64 תווי hex שנגזרו מהנתיבים ומהתוכן (ולא מהזמן), כדי
  // ששתי אריזות של אותה מראה ייתנו אותה חותמת. זה מה שמשווים למה שרשום
  // ב-`Data\bundle.stamp` כדי לדעת אם התיקייה שליד ה-exe היא כבר של
  // החבילה הזאת.
  std::string stamp;
};

// מדווח כמה בייטים מהתוכן כבר נכתבו. נקרא **הרבה** — אחרי כל גוש, ולא
// אחרי כל קובץ — כדי שקובץ בודד גדול לא ייראה כתקיעה.
//
// אין כאן שם הקובץ הנוכחי במכוון: שם שמתחלף עשרות פעמים בשנייה הוא
// רעש, וכשל ממילא חוזר עם הנתיב בתוך הודעת השגיאה.
using ProgressFn = std::function<void(uint64_t done, uint64_t total)>;

// קורא את ה-footer ומאמת אותו. **קובץ בלי חבילה אינו שגיאה** — זה המצב
// של ה-exe הרזה, כלומר של רוב ההרצות — ולכן `false` כאן שקט לגמרי.
bool HasOverlay(const std::wstring& exe_path, OverlayInfo& out);

// פורס את המטען אל [data_dir], **בזרימה**: חוצץ קבוע אחד, בלי שאף קובץ
// (ובוודאי לא המטען כולו) ייטען לזיכרון. תיקיות נוצרות לפי הצורך.
//
// אינו מוחק דבר — הניקוי שלפניו הוא החלטה של הקורא, ראו main.cpp.
bool ExtractOverlay(const std::wstring& exe_path, const OverlayInfo& info,
                    const std::wstring& data_dir, const ProgressFn& on_progress,
                    std::wstring& error);

// כותב ל-[dest] את [data_offset] הבייטים הראשונים של [exe_path] — כלומר
// את ה-exe בלי המטען.
//
// ⚠️ בווינדוס **קריאה** מקובץ ההרצה של התהליך הרץ מותרת, אבל כתיבה
// אליו אינה. הקורא חייב לוודא ש-[dest] אינו אנחנו עצמנו; כאן זה לא
// נבדק, כי מהמקום הזה כבר אין מה לעשות עם התשובה.
bool WriteSlimCopy(const std::wstring& exe_path, uint64_t data_offset,
                   const std::wstring& dest, std::wstring& error);

// מוחק תיקייה על כל תוכנה. תיקייה שאינה קיימת היא הצלחה — המצב המבוקש
// הושג.
//
// ⚠️ יושב כאן ולא ב-fsapi בכוונה: `fsapi.h` הוא **מה שהגשר חושף ל-JS**,
// ומחיקה רקורסיבית אינה פעולה שצריכה להיות זמינה לממשק. המשתמש היחיד
// שלה הוא ההחלפה הסיטונית של המראה.
bool RemoveTree(const std::wstring& path);

// מריץ את [exe_path] ולא ממתין לו. זו מסירת השרביט לעותק הרזה: החבילה
// יוצאת מיד אחריה.
bool LaunchAndForget(const std::wstring& exe_path, std::wstring& error);

// תוכן `Data\bundle.stamp` — שתי שורות, ומכאן שאין כאן פרסור אמיתי.
//
// למה קובץ טקסט שטוח ולא JSON: הצד ה-C++ אינו מפרסר JSON בכלל (ראו
// common.h), והקובץ הזה נקרא **לפני** שהממשק עולה — כלומר לפני שיש מי
// שיפרסר בשבילנו.
struct StampFile {
  // שורה 1 — חותמת החבילה שממנה נפרסה התיקייה.
  std::string stamp;

  // שורה 2 — הנתיב המלא של החבילה שפרסה אותה, כפי שהיה בזמן הפריסה.
  // ריק בקובץ שנכתב בגרסה שלא רשמה אותו.
  std::wstring installer;
};

bool ReadStampFile(const std::wstring& path, StampFile& out);
bool WriteStampFile(const std::wstring& path, const StampFile& value,
                    std::wstring& error);

// חלון ההתקדמות של הפריסה — Win32 חשוף, **בלי WebView2**.
//
// ⚠️ למה לא הממשק הרגיל: הפריסה קורית לפני שה-WebView2 עולה בכלל (הוא
// לוקח מאות ms בעצמו, וממילא הממשק צריך `Data\` פרוסה כדי להראות משהו).
// ‎96MB לכונן USB הם 3-20 שניות, ומסך ריק לאורך זמן כזה נראה כמו תוכנה
// תקועה. חלון Win32 עם progress bar עולה בפחות מ-10ms.
//
// אין כפתור סגירה ואין ביטול: פעולה של פחות מדקה שאין לה מצב ביניים
// מזיק (ראו ההסבר על החותמת בראש הקובץ) לא מרוויחה מהם.
class ProgressWindow {
 public:
  ~ProgressWindow() { Close(); }

  // יוצר ומציג. `false` = לא נוצר — הקורא ממשיך בלי חלון ולא נכשל
  // בגללו: פריסה בלי חיווי עדיפה על אי-פריסה.
  bool Create(HINSTANCE instance, const std::wstring& title,
              const std::wstring& headline);

  // מעדכן את המחוון **וממחזר את תור ההודעות**. ראו [Pump] ב-overlay.cpp.
  void Update(uint64_t done, uint64_t total);

  void Close();

 private:
  // מרוקן את תור ההודעות של החלון. הפריסה חוסמת את ה-thread הזה, ובלי
  // זה ווינדוס הייתה מסמנת את החלון כ"אינו מגיב" ומציירת עליו רפאים.
  void Pump();

  HWND window_ = nullptr;
  HWND bar_ = nullptr;
  HWND detail_ = nullptr;
  HFONT font_ = nullptr;

  // האחוז שכבר מצויר. עדכון רק כשהוא משתנה — אחרת כל גוש של ‎1MB היה
  // מפעיל ציור מחדש של אותו טקסט בדיוק.
  int shown_percent_ = -1;
};

}  // namespace otz
